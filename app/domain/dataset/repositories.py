from collections.abc import AsyncIterator
from typing import Protocol
from uuid import UUID

from .entities import Dataset, Example, Export, Revision


class DatasetRepository(Protocol):
    async def add(self, dataset: Dataset) -> Dataset: ...

    async def get(self, dataset_id: UUID, *, for_update: bool = False) -> Dataset | None: ...

    async def list(self, *, offset: int, limit: int) -> tuple[list[Dataset], int]: ...

    async def save(self, dataset: Dataset) -> None: ...


class ExampleRepository(Protocol):
    async def add(self, example: Example) -> Example: ...

    async def get(self, example_id: UUID, *, for_update: bool = False) -> Example | None: ...

    async def list_by_dataset(
        self, dataset_id: UUID, *, offset: int, limit: int
    ) -> list[tuple[Example, Revision | None]]: ...

    async def save(self, example: Example) -> None: ...


class RevisionRepository(Protocol):
    async def add(self, revision: Revision) -> Revision: ...

    async def get(self, revision_id: UUID, *, for_update: bool = False) -> Revision | None: ...

    async def latest_number(self, example_id: UUID) -> int: ...

    async def save(self, revision: Revision) -> None: ...


class ExportRepository(Protocol):
    async def add(self, export: Export) -> Export: ...

    async def get(self, export_id: UUID, *, for_update: bool = False) -> Export | None: ...

    async def save(self, export: Export) -> None: ...

    def stream_eligible_revisions(self, dataset_id: UUID) -> AsyncIterator[Revision]: ...
